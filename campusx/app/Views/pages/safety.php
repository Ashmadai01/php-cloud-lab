<div class="container"><div class="page-head"><h1>Safety Tips</h1></div>
<div class="panel" style="max-width:820px">
<h3>Meet on campus</h3><p>Always meet in a public, well-lit campus location — library, student center, or campus security office. Bring a friend for high-value items.</p>
<h3>Inspect before you pay</h3><p>Check the item matches its description. Test electronics on the spot. Never pay in advance.</p>
<h3>Keep chat on SDUT Swap</h3><p>Don't share phone numbers, social media handles, or bank details in chat. Scammers often ask to move off-platform.</p>
<h3>Trust your instincts</h3><p>If a deal seems too good to be true, it probably is. Report suspicious listings, users, or messages immediately.</p>
<h3>Protect your privacy</h3><p>Don't post your home address or personal documents in listings or photos.</p>
